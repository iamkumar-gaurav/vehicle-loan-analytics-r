# ==================================================
# Lesson 3: Introduction to Vectors in R
# ==================================================
# A vector is a basic data structure in R used
# to store multiple values in a single variable.
#
# The c() function combines values into a vector.
# Elements in a vector must have the same data type.
# Vector indexing starts at 1.
#
# Project Example:
# Store multiple vehicle loan amounts in one vector.
# ==================================================

loan_request <- c(250000,400000,550000)

print(loan_request)
